/** @file
    This file provides some utility functions related to the console input/output.
    @ingroup util
 */

#pragma once

#include <string_view>
#include <variant>

/** This namespace provides general utilities not specific to chess.
    @ingroup util
 */
namespace util {

/** Ensures that ``std::cout`` will interpret strings as UTF-8.
    On non-Windows platforms, this is a no-op.

    @ingroup util
 */
void enable_utf8_console_output();

/** This simple function prints an error message to ``stderr``
    and returns a monostate object, making it suitable for passing
    directly to functions such as ``std::expected::transform_error``.

    @ingroup util
 */
auto print_error(std::string_view message) -> std::monostate;

} // namespace util

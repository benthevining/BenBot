#include <filesystem>
#include <format>
#include <fstream>
#include <ios>
#include <stdexcept>
#include <string>
#include <tuner/Model.hpp>
#include <tuner/Writer.hpp>

namespace ben_bot::tuner {

void write_weights(const std::filesystem::path& path, const Params& params)
{
    const auto source = round_params(params).to_cpp();

    auto temporary = path;

    temporary += ".tmp";

    {
        std::ofstream output { temporary, std::ios::binary | std::ios::trunc };

        if (not output.is_open())
            throw std::runtime_error { std::format("Can't write to '{}'", temporary.string()) };

        output << source;

        if (not output.good())
            throw std::runtime_error { std::format("Failed writing '{}'", temporary.string()) };
    }

    std::filesystem::rename(temporary, path);
}

} // namespace ben_bot::tuner

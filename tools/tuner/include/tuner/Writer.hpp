namespace ben_bot::tuner {

/** Rounds the parameters to integers and writes them to ``path`` with ``eval::Weights::to_cpp()``,
    so that the file can replace ``libbenbot/include/libbenbot/eval/DefaultWeights.hpp``.

    The file is written to a temporary file next to ``path`` first and then renamed, so
    that an interrupted run never leaves a half-written file.
    Throws ``std::runtime_error`` if the file can't be written.

    @ingroup tuner
 */
void write_weights(const std::filesystem::path& path, const Params& params);

} // namespace ben_bot::tuner

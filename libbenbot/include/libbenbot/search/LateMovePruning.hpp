/** @file
    This file defines the parameters of late move pruning.
    @ingroup search
 */

#pragma once

#include <cstddef> // IWYU pragma: keep - for size_t

namespace ben_bot::search {

using std::size_t;

/** Late move pruning is only done with at most this much depth left.
    @ingroup search
 */
inline constexpr auto LMP_MAX_DEPTH { 7uz };

/** Returns the number of moves to search before late move pruning starts skipping quiet moves.

    This is ``(3 + d^2) / (2 - improving)``, where ``d`` is depth as other engines count it:
    a frontier node (``depthLeft == 0``) is depth 1. So nodes that aren't improving search
    about half as many moves before pruning starts. This is always at least 2, so the first
    move is never pruned. It uses integer maths only, so that bench is the same on every platform.

    @ingroup search
 */
[[nodiscard]] constexpr auto lmp_move_count(const size_t depthLeft, const bool improving) noexcept -> size_t
{
    const auto depth = depthLeft + 1uz;

    return (3uz + (depth * depth)) / (improving ? 1uz : 2uz);
}

} // namespace ben_bot::search

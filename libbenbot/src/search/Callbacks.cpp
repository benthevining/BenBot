#include <functional>
#include <libbenbot/search/Callbacks.hpp>
#include <libbenbot/search/Result.hpp>
#include <libchess/uci/Printing.hpp>

namespace ben_bot::search {

auto Callbacks::make_uci_printer(
    std::function<bool()> isDebugMode)
    -> Callbacks
{
    namespace uci_printing = chess::uci::printing;

    // clang-format off
    return {
        .onSearchComplete = [isDebugMode](const Result& res) {
            uci_printing::search_info(res.to_libchess(isDebugMode()));
            uci_printing::best_move(res.best_move(), res.ponder_move()); },
        .onIteration      = [isDebugMode](const Result& res) {
            uci_printing::search_info(res.to_libchess(isDebugMode()));
        }
    };
    // clang-format on
}

} // namespace ben_bot::search

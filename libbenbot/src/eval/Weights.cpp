namespace ben_bot::eval {

using std::string;
using std::string_view;

namespace {

    // the name of each piece type's table, in the order they're stored in
    inline constexpr std::array PST_NAMES {
        std::pair { PieceType::Pawn, string_view { "pawn" } },
        std::pair { PieceType::Knight, string_view { "knight" } },
        std::pair { PieceType::Bishop, string_view { "bishop" } },
        std::pair { PieceType::Rook, string_view { "rook" } },
        std::pair { PieceType::Queen, string_view { "queen" } },
        std::pair { PieceType::King, string_view { "king" } }
    };

    inline constexpr auto VALUES_PER_LINE = 8uz;

    // the C++ comment block holding the license header
    [[nodiscard]] auto license_comment() -> string
    {
        string result { "/*\n" };

        auto text = resources::get_ascii_logo();

        while (not text.empty()) {
            const auto newline = text.find('\n');

            const auto line = text.substr(0uz, newline);

            if (line.empty())
                result.append(" *\n");
            else
                result.append(std::format(" * {}\n", line));

            if (newline == string_view::npos)
                break;

            text.remove_prefix(newline + 1uz);
        }

        result.append(" */\n");

        return result;
    }

    [[nodiscard]] auto format_value(const TaperedScore value) -> string
    {
        return std::format("S({}, {}),", value.mg, value.eg);
    }

    // writes the values in rows, with the columns aligned
    void append_values(string& output, const std::span<const TaperedScore> values)
    {
        const auto width = std::ranges::max(
            values | std::views::transform([](const TaperedScore value) { return format_value(value).size(); }));

        for (auto i = 0uz; i < values.size(); ++i) {
            const bool startOfLine = i % VALUES_PER_LINE == 0uz;
            const bool endOfLine   = (i + 1uz) % VALUES_PER_LINE == 0uz or i + 1uz == values.size();

            if (startOfLine)
                output.append("        ");

            const auto text = format_value(values[i]);

            output.append(text);

            if (endOfLine)
                output.push_back('\n');
            else
                output.append(width - text.size() + 1uz, ' ');
        }
    }

} // namespace

auto Weights::to_cpp() const -> string
{
    auto output = license_comment();

    output.append(R"(
// This file is generated by ben_bot::eval::Weights::to_cpp(). The unit tests check that
// to_cpp() reproduces it exactly, so change the weights & regenerate it instead of
// editing it by hand.

/** @file
    This file defines the default eval weights.
    @ingroup eval
 */

#pragma once

#include <array>
#include <libbenbot/eval/TaperedScore.hpp>
#include <libbenbot/eval/Weights.hpp>

namespace ben_bot::eval {

namespace detail {
    [[nodiscard]] consteval auto S(const int mg, const int eg) noexcept -> TaperedScore
    {
        return { .mg = mg, .eg = eg };
    }
} // namespace detail

// clang-format off

/** The default eval weights.
    The eval reads these as compile-time constants.

    @ingroup eval
 */
// std::to_array() only converts to Weights::values if there are exactly NUM_WEIGHTS values here
inline constexpr Weights DEFAULT_WEIGHTS = [] {
    using detail::S;

    return Weights { .values = std::to_array<TaperedScore>({
)");

    for (const auto& info : TERMS) {
        if (info.term == Term::Pst) {
            for (const auto& [type, tag] : PST_NAMES) {
                output.append(std::format("        // {} ({})\n", info.name, tag));

                append_values(output, pst(type));
            }
        } else {
            output.append(std::format("        // {}\n", info.name));

            append_values(output, of_term(info.term));
        }
    }

    output.append(R"(    }) };
}();

// these fail if the term registry changes, until this file is regenerated
)");

    for (const auto& info : TERMS) {
        output.append(std::format(
            "static_assert(offset_of(Term::{}) == {}uz);\n",
            magic_enum::enum_name(info.term), offset_of(info.term)));
    }

    output.append(std::format(
        "static_assert(NUM_WEIGHTS == {}uz);\n"
        "\n"
        "// clang-format on\n"
        "\n"
        "}} // namespace ben_bot::eval\n",
        NUM_WEIGHTS));

    return output;
}

} // namespace ben_bot::eval

/** @file
    This file defines a chessboard widget that renders a position.
    @ingroup libgui
 */

#pragma once

#include <libchess/game/Position.hpp>
#include <libgui/PieceTextures.hpp>

namespace ben_bot::gui {

using chess::game::Position;

/** Renders a chessboard displaying the given position, from White's perspective.

    The board is drawn as a square filling as much of the available content
    region as possible. Each square is submitted as its own (invisible) item.

    If the piece texture hasn't been created, pieces are drawn as letters instead
    of sprites.

    @ingroup libgui
    @relates PieceTextures
 */
void render_chessboard(
    const Position&      position,
    const PieceTextures& pieceTextures);

} // namespace ben_bot::gui
